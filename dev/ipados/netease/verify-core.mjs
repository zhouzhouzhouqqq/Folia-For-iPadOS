import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import zlib from 'node:zlib';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';

// Independent Node/desktop oracle for Swift EAPI, WEAPI, XEAPI, form encoding and gzip compatibility.
const require = createRequire(import.meta.url);
const upstream = require('@neteasecloudmusicapienhanced/api/util/crypto');
const work = path.resolve('../../work/netease-direct');
fs.mkdirSync(work, { recursive: true });
const peer = crypto.generateKeyPairSync('x25519');
const keyState = { version: 17, sk: 'fixture-only-exchange-secret', publicKey: peer.publicKey.export({ format: 'der', type: 'spki' }).subarray(-32).toString('base64') };
const data = { title: '歌词 + & / 🎵', flag: true, number: 42, nothing: null };
const fixture = path.join(work, 'crypto-fixture.json');
fs.writeFileSync(fixture, JSON.stringify({ data, keyState, gzip: zlib.gzipSync('animated lyrics / 歌词').toString('base64') }));
const swift = ['NeteaseCrypto', 'NeteaseState', 'NeteaseHTTP', 'NeteaseClient', 'NeteaseBootstrap'].map(name => `ios/App/App/Netease/${name}.swift`);
const executable = path.join(work, 'core-probe');
execFileSync('xcrun', ['swiftc', '-swift-version', '5', ...swift, 'dev/ipados/netease/CoreProbe.swift', '-o', executable], { stdio: 'inherit' });
const result = JSON.parse(execFileSync(executable, [fixture], { encoding: 'utf8' }));
const decrypted = upstream.eapiReqDecrypt(result.eapi.params);
assert.equal(decrypted.url, '/api/test/native');
assert.deepEqual(decrypted.data, data);
const sortedJSON = JSON.stringify(Object.fromEntries(Object.entries(data).sort(([a], [b]) => a.localeCompare(b))));
const first = upstream.aesEncrypt(sortedJSON, 'cbc', '0CoJUm6Qyw8W8jud', '0102030405060708');
assert.equal(result.weapi.params, upstream.aesEncrypt(first, 'cbc', '0123456789abcdef', '0102030405060708'));
const forge = require('node-forge');
const pem = `-----BEGIN PUBLIC KEY-----\nMIGfMA0GCSqGSIb3DQEBAQUAA4GNADCBiQKBgQDgtQn2JZ34ZC28NWYpAUd98iZ37BUrX/aKzmFbt7clFSs6sXqHauqKWqdtLkF2KexO40H1YTX8z2lSgBBOAxLsvaklV8k4cBFK9snQXE9/DDaFt6Rr7iVZMldczhC0JNgTz+SHXT6CBHuX3e9SdB1Ua44oncaTWz7OBGLbCiK45wIDAQAB\n-----END PUBLIC KEY-----`;
assert.equal(result.weapi.encSecKey, forge.util.bytesToHex(forge.pki.publicKeyFromPem(pem).encrypt('fedcba9876543210', 'NONE')));
const sealed = Buffer.from(result.xeapi.S, 'base64');
const ephemeral = crypto.createPublicKey({ key: Buffer.concat([Buffer.from('302a300506032b656e032100', 'hex'), sealed.subarray(0, 32)]), format: 'der', type: 'spki' });
const shared = crypto.diffieHellman({ privateKey: peer.privateKey, publicKey: ephemeral });
const prk = crypto.createHmac('sha256', Buffer.alloc(32)).update(shared).digest();
const aesKey = crypto.createHmac('sha256', prk).update(Buffer.concat([sealed.subarray(0, 32), Buffer.from([1])])).digest().subarray(0, 16);
const decipher = crypto.createDecipheriv('aes-128-gcm', aesKey, sealed.subarray(32, 44));
decipher.setAuthTag(sealed.subarray(-16));
const secret = Buffer.concat([decipher.update(sealed.subarray(44, -16)), decipher.final()]).toString().split('|');
assert.deepEqual(secret.slice(1), ['android', keyState.sk]);
const decryptECB = (key, data) => { const d = crypto.createDecipheriv(`aes-${key.length * 8}-ecb`, key, null); return Buffer.concat([d.update(data), d.final()]); };
const staticKey = Buffer.from('ab1d5a430f6bb04a3f01e81ddd72bd916d5ce591248ac128714806d7f8fb1b84', 'hex');
const middle = decryptECB(Buffer.from(secret[0], 'base64'), Buffer.from(result.xeapi.C, 'base64url'));
const mask = middle.subarray(0, 16), rotated = middle.subarray(16);
const rotation = (mask[0] & 15) % rotated.length;
const original = rotation ? Buffer.concat([rotated.subarray(-rotation), rotated.subarray(0, -rotation)]) : rotated;
const inner = Buffer.from(original.map((byte, i) => byte ^ mask[i & 15]));
const payload = JSON.parse(decryptECB(staticKey, inner));
assert.equal(payload.queryString, 'e_r=true');
assert.equal(payload.content, result.form);
assert.equal(decryptECB(staticKey, Buffer.from(result.xeapi.R, 'base64')).toString(), '17|');
assert.equal(result.inflated, 'animated lyrics / 歌词');
assert.deepEqual(Object.fromEntries(new URLSearchParams(result.form)), Object.fromEntries(Object.entries(data).map(([key, value]) => [key, String(value)])));
console.log('PASS: Swift EAPI/WEAPI/RSA/X25519/HMAC/AES-GCM/XEAPI envelope/gzip/form match independent desktop/Node oracles.');
console.log(`Probe binary: ${executable}`);

const testExecutable = path.join(work, 'core-tests');
execFileSync('xcrun', ['swiftc', '-swift-version', '5', ...swift, 'dev/ipados/netease/CoreTests.swift', '-o', testExecutable], { stdio: 'inherit' });
execFileSync(testExecutable, [], { stdio: 'inherit' });
