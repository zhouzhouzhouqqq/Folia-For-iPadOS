import { readFileSync, writeFileSync } from 'node:fs';

// Keep a browser-safe ESM mirror of the original provider engine; no manual edits or runtime require in WKWebView.
export function browserAIClient(source) {
    return source.replace('"use strict";', '// Generated by dev/ipados/ai/sync-client.mjs from aiTextClient.cjs.')
        .replace("const { REASONING_SUPPRESSION_ATTEMPTS } = require('./lyricSegmentationPrompt.cjs');",
            "import { REASONING_SUPPRESSION_ATTEMPTS } from './lyricSegmentationPrompt.mjs';")
        .replace('module.exports = {', 'export {');
}
if (process.argv[1]?.endsWith('/sync-client.mjs')) {
    const generated = browserAIClient(readFileSync('shared/aiTextClient.cjs', 'utf8'));
    if (process.argv.includes('--check')) {
        if (readFileSync('shared/aiTextClient.mjs', 'utf8') !== generated) throw new Error('AI client mirror is stale');
    } else writeFileSync('shared/aiTextClient.mjs', generated);
}
