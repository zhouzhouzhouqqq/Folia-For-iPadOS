import { readFileSync, writeFileSync } from 'node:fs';
import { build } from 'esbuild';

// Bundle the upstream pure AI clients and model discovery for WKWebView; no Node runtime or keys.
export async function browserAIClient() {
    const result = await build({
        stdin: { contents: `import client from './electron/aiTextClient.cjs';
import discovery from './electron/ai/modelDiscovery.cjs';
export const { runAiJsonCompletion, runAiConnectionTest, aiProviderLabel, normalizeOpenAIChatCompletionsUrl,
    resolveFormAdapter, validateAiConnectionTestInput, createOpenAIStreamAccumulator } = client;
export const { listAiModels, modelListUrl } = discovery;`, resolveDir: process.cwd() },
        bundle: true, write: false, platform: 'browser', format: 'esm', target: 'safari18',
        banner: { js: '// Generated by dev/ipados/ai/sync-client.mjs from upstream electron/aiTextClient.cjs and electron/ai/.' },
        legalComments: 'eof',
    });
    return result.outputFiles[0].text;
}
if (process.argv[1]?.endsWith('/sync-client.mjs')) {
    const generated = await browserAIClient();
    if (process.argv.includes('--check')) {
        if (readFileSync('shared/aiTextClient.mjs', 'utf8') !== generated) throw new Error('AI client mirror is stale');
    } else writeFileSync('shared/aiTextClient.mjs', generated);
}
