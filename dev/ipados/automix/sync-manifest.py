#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the native-only model constants from Folia's canonical manifest (no desktop Python archive)."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[3]
manifest = json.loads((root / 'shared/ipadosModelManifest.json').read_text())
rows = [m for m in manifest['models'] if m['name'] in ('beat_this', 'htdemucs')]
text = '// Generated by dev/ipados/automix/sync-manifest.py from shared/ipadosModelManifest.json.\nimport Foundation\n\n// Public MIT weights only. No account, media or credential is sent to these mirrors.\nstruct AutomixModel: Sendable {\n    let name: String, file: String, bytes: Int, sha256: String\n    static let all: [AutomixModel] = [\n'
for m in rows:
    text += f'        .init(name: "{m["name"]}", file: "{m["file"]}", bytes: {m["bytes"]}, sha256: "{m["sha256"]}"),\n'
text += '    ]\n    static let mirrors = [\n' + ''.join(f'        "{v}",\n' for v in manifest['mirrors']) + '    ]\n}\n'
target = root / 'ios/App/App/Automix/AutomixModelManifest.swift'
if '--check' in __import__('sys').argv:
    assert target.read_text() == text, 'Run python3 dev/ipados/automix/sync-manifest.py'
else:
    target.write_text(text)
